import random
from datetime import datetime, timedelta
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from app.database import get_db
from app.models.batch import MedicineBatch
from app.schemas import TemperatureIn
from app.auth.dependencies import require_role
from app.utils.coldchain import add_reading, coldchain_summary
from app.utils.ids import parse_uuid

router = APIRouter(prefix="/coldchain", tags=["coldchain"])
WRITERS = ["manufacturer", "distributor", "pharmacy", "admin"]


def get_cold_batch(db: Session, batch_uid: str):
    b = db.query(MedicineBatch).filter(
        MedicineBatch.batch_uid == parse_uuid(batch_uid, "batch ID")
    ).first()
    if not b:
        raise HTTPException(status_code=404, detail="Batch not found")
    if not b.requires_cold_chain:
        raise HTTPException(status_code=400, detail="This batch is not marked as a cold-chain batch")
    return b


# This is the endpoint a real IoT temperature logger would call.
# There is no hardware in this project, so readings are entered by hand
# or generated by /simulate below.
@router.post("/readings")
def post_reading(r: TemperatureIn, db: Session = Depends(get_db),
                 user=Depends(require_role(WRITERS))):
    b = get_cold_batch(db, r.batch_uid)
    row = add_reading(db, b, user["user_id"], r.temperature_c, r.location, r.device_id)
    return {
        "message": "Reading saved",
        "temperature_c": row.temperature_c,
        "breach": row.is_breach,
        "range": f"{b.min_temp:g} to {b.max_temp:g} °C",
    }


# Simulated sensor: creates a journey's worth of readings (optionally with one excursion)
@router.post("/simulate/{batch_uid}")
def simulate(batch_uid: str, breach: bool = False, db: Session = Depends(get_db),
             user=Depends(require_role(WRITERS))):
    b = get_cold_batch(db, batch_uid)
    mid = (b.min_temp + b.max_temp) / 2
    span = (b.max_temp - b.min_temp) / 2
    places = ["Manufacturer facility", "In transit", "Distributor warehouse",
              "In transit", "Pharmacy storage", "Pharmacy storage"]
    now = datetime.now()
    for i, place in enumerate(places):
        t = round(mid + random.uniform(-0.6 * span, 0.6 * span), 1)
        if breach and i == 3:
            t = round(b.max_temp + random.uniform(3, 7), 1)  # excursion during transit
        add_reading(db, b, user["user_id"], t, place, "SIM-SENSOR-01",
                    now - timedelta(hours=(len(places) - i) * 2))
    return {"message": f"{len(places)} simulated readings saved" + (" (including a breach)" if breach else "")}


@router.get("/{batch_uid}")
def get_log(batch_uid: str, db: Session = Depends(get_db)):
    b = db.query(MedicineBatch).filter(
        MedicineBatch.batch_uid == parse_uuid(batch_uid, "batch ID")
    ).first()
    if not b:
        raise HTTPException(status_code=404, detail="Batch not found")
    return coldchain_summary(db, b)
